def test_list_newest_books(mock_db_session):
    # Add test data to the database
    mock_db_session.add_all([
        Book(title="Book 1", author="Author 1", pages=100, created_at=datetime.datetime.now() - datetime.timedelta(days=30), popularity=5.0),
        Book(title="Book 2", author="Author 2", pages=200, created_at=datetime.datetime.now() - datetime.timedelta(days=120), popularity=10.0),
        Book(title="Book 3", author="Author 3", pages=150, created_at=datetime.datetime.now() - datetime.timedelta(days=60), popularity=7.0)
    ])
    mock_db_session.commit()
    response = client.get("/books/newest")
    assert response.status_code == 200
    books = response.json()
    assert len(books) == 2
    assert books[0]['title'] == "Book 1"
    assert books[1]['title'] == "Book 3"
